"""Build flows/ruian-agent.json: a chat agent that answers questions with the RUIAN Search tools.

Flow: Chat Input -> Agent <- RUIAN Search (Toolset) ; Agent -> Chat Output.
All node templates are generated by lfx: Chat Input, Agent and Chat Output from the installed lfx
components, RUIAN Search from components/ruian_search_component.py (so the flow embeds its code).
Edge handles are derived from the nodes' outputs and input fields, so they cannot drift from the
templates (Langflow's UI drops edges whose handles do not match, then saves the flow).
The Agent uses the "OpenAI Compatible" model provider with LLM_MODEL from the environment (default
openrouter-gemma); base URL and API key are Langflow global variables (see scripts/agent_llm.py).

Usage: [LLM_MODEL=...] uv run python scripts/build_ruian_agent_flow.py
"""

import json
from pathlib import Path

from agent_llm import configure_agent_model, edge
from lfx.base.tools.constants import TOOL_OUTPUT_NAME
from lfx.components.input_output.chat import ChatInput
from lfx.components.input_output.chat_output import ChatOutput
from lfx.components.models_and_agents.agent import AgentComponent
from lfx.custom.utils import create_component_template

ROOT = Path(__file__).resolve().parent.parent
COMPONENT = ROOT / "components" / "ruian_search_component.py"
OUT = ROOT / "flows" / "ruian-agent.json"

FLOW_ID = "c3a91e4d-6f2b-4d8e-b1a7-9e5d2f0c7a34"  # stable, so `lfx push` upserts
CHAT_IN_ID = "ChatInput-a1b2c"
AGENT_ID = "Agent-d3e4f"
CHAT_OUT_ID = "ChatOutput-g5h6i"
SEARCH_ID = "RuianSearch-ru1an"

SYSTEM_PROMPT = """You answer questions about Czech addresses using the RUIAN address register tools.

You know nothing about the register yourself. Before you answer, call at least one tool. Every address, \
id, postal code, count, coordinate and distance in your answer must come from a tool result in this \
conversation. If the tools do not give it, say that you could not find it.

How to work:
- For a written address ("Vodičkova 36, Praha", "Bukovina 5, 679 05"), call search_address with it first. \
Leave out words that are not part of the address. It returns the matching address places in one call.
- For other questions, resolve names to ids: search_municipality, then search_street, \
search_municipality_part or search_city_district filtered by municipality_id_in, then \
search_address_place filtered by the ids you found. Names are not unique: always filter by the municipality.
- Search names in the nominative ("Brno", not "Brně"; "Praha", not "Praze") or with a distinctive prefix \
("nadraz" finds "Nádražní"). Case and diacritics are ignored.
- name_mode: for "names starting with X" use starts_with; for "named exactly X" use exact. The default \
word_prefix also finds names where any word starts with X ("Nad nádražím" for "nádraž").
- For "how many" questions use the total of the result, not the number of returned items. If \
total_is_lower_bound is true, say "more than <total>".
- In "Vodičkova 704/36", 704 is the building number and 36 the orientation number.
- For distances, find the address ids with search_address, then use address_distances (one origin, up to \
100 targets) or search_nearby (addresses within a radius, nearest first). These are straight-line (as the \
crow flies) distances: always say so when you report one, and never present them as road or walking distances.
- If a search returns nothing, try a shorter prefix or drop a filter before you say it does not exist.
- When has_more is true, the item list is incomplete: say so, or page with offset.
- Show addresses with the 'formatted' field. Address places have WGS84 coordinates in 'lat' and 'lon'. \
Never invent addresses, ids, counts or coordinates that the tools did not return.

Answer in the language of the user."""


def node(node_id: str, node_type: str, tpl: dict, x: int, y: int) -> dict:
    return {
        "id": node_id,
        "type": "genericNode",
        "position": {"x": x, "y": y},
        "data": {"id": node_id, "type": node_type, "node": tpl, "showNode": True},
    }


def builtin_node(node_id: str, cls, module_name: str, x: int, y: int) -> dict:
    tpl, _ = create_component_template(component_extractor=cls(), module_name=module_name)
    return node(node_id, cls.name, tpl, x, y)


def search_node() -> dict:
    code = COMPONENT.read_text(encoding="utf-8")
    tpl, _ = create_component_template({"code": code, "output_types": []})
    # The component declares the Toolset output itself; the Agent's `tools` input connects to it.
    outputs = [o["name"] for o in tpl["outputs"]]
    assert outputs == [TOOL_OUTPUT_NAME], f"unexpected outputs {outputs}"
    # Langflow checks the stored node before every tool call and refuses the call unless the node is in
    # tool mode ("Tool settings changed or are unavailable"; langflow AuthService.validate_tool_call).
    tpl["tool_mode"] = True
    return node(SEARCH_ID, "RuianSearch", tpl, 0, 420)


def connect(src: dict, output_name: str, tgt: dict, field_name: str) -> dict:
    """Edge from an output to an input field, with both handles taken from the node templates."""
    output = next(o for o in src["data"]["node"]["outputs"] if o["name"] == output_name)
    field = tgt["data"]["node"]["template"][field_name]
    output_types, input_types = output["types"], field.get("input_types") or []
    assert set(output_types) & set(input_types), f"{output_name} {output_types} does not fit {field_name} {input_types}"
    return edge(
        src["id"], {"dataType": src["data"]["type"], "id": src["id"], "name": output_name, "output_types": output_types},
        tgt["id"], {"fieldName": field_name, "id": tgt["id"], "inputTypes": input_types, "type": field["type"]},
    )


def main() -> None:
    chat_in = builtin_node(CHAT_IN_ID, ChatInput, "lfx.components.input_output.chat", 0, 0)
    agent = builtin_node(AGENT_ID, AgentComponent, "lfx.components.models_and_agents.agent", 500, 0)
    chat_out = builtin_node(CHAT_OUT_ID, ChatOutput, "lfx.components.input_output.chat_output", 1000, 0)
    search = search_node()
    agent["data"]["node"]["template"]["system_prompt"]["value"] = SYSTEM_PROMPT
    model = configure_agent_model(agent)

    edges = [
        connect(chat_in, "message", agent, "input_value"),
        connect(search, TOOL_OUTPUT_NAME, agent, "tools"),
        connect(agent, "response", chat_out, "input_value"),
    ]

    flow = {
        "data": {"edges": edges, "nodes": [chat_in, agent, search, chat_out], "viewport": {"x": 100, "y": 50, "zoom": 0.8}},
        "description": (
            "Chat agent over the RUIAN address register. Tools come from the RUIAN Search component, "
            f"the model from the OpenAI Compatible provider ({model})."
        ),
        "endpoint_name": "ruian-agent",
        "icon": "map-pin",
        "icon_bg_color": None,
        "id": FLOW_ID,
        "is_component": False,
        "locked": False,
        "mcp_enabled": False,
        "name": "ruian-agent",
        "tags": [],
        "webhook": False,
    }
    # Sorted keys: the same bytes as `lfx pull`, so pulling the flow back from Langflow gives no diff.
    OUT.write_text(json.dumps(flow, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {OUT} (model {model})")


if __name__ == "__main__":
    main()
