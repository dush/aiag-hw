"""Build flows/ruian-agent.json: a chat agent that answers questions with the RUIAN Search tools.

Flow: Chat Input -> Agent <- RUIAN Search (Toolset) ; Agent -> Chat Output.
Chat Input, Agent and Chat Output are copied from flows/simple-agent.json. The RUIAN Search node is
generated by lfx from components/ruian_search_component.py, so the flow embeds the component code.
The Agent uses the "OpenAI Compatible" model provider with LLM_MODEL from the environment (default
openrouter/free); base URL and API key are Langflow global variables (see scripts/agent_llm.py).

Usage: [LLM_MODEL=...] uv run python scripts/build_ruian_agent_flow.py
"""

import copy
import json
from pathlib import Path

from agent_llm import configure_agent_model, edge
from lfx.base.tools.constants import TOOL_OUTPUT_NAME
from lfx.custom.utils import create_component_template

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "flows" / "simple-agent.json"
COMPONENT = ROOT / "components" / "ruian_search_component.py"
OUT = ROOT / "flows" / "ruian-agent.json"

FLOW_ID = "c3a91e4d-6f2b-4d8e-b1a7-9e5d2f0c7a34"  # stable, so `lfx push` upserts
SEARCH_ID = "RuianSearch-ru1an"

SYSTEM_PROMPT = """You answer questions about Czech addresses using the RUIAN address register tools.

How to work:
- Names are not unique. Resolve them to ids first: search_municipality, then search_street, \
search_municipality_part or search_city_district filtered by municipality_id_in, then \
search_address_place filtered by the ids you found.
- name_match ignores case and diacritics and treats every word as a prefix, so search with the \
distinctive part of a name ("nadraz" finds "Nádražní"). Do not include house numbers or postal codes \
in name_match; use the building_number, orientation_number and postal_code_in filters.
- In "Vodičkova 704/36", 704 is the building number and 36 the orientation number. A single number \
on a street is usually the orientation number in cities and the building number in villages; try both.
- If a search returns nothing, try a shorter prefix or drop a filter before you say it does not exist.
- When has_more is true, the list is incomplete: say so, or page with offset.
- Show addresses with the 'formatted' field. Never invent addresses, ids or counts that the tools did \
not return.

Answer in the language of the user."""


def search_node() -> dict:
    code = COMPONENT.read_text(encoding="utf-8")
    tpl, _ = create_component_template({"code": code, "output_types": []})
    # The component declares the Toolset output itself; the Agent's `tools` input connects to it.
    outputs = [o["name"] for o in tpl["outputs"]]
    assert outputs == [TOOL_OUTPUT_NAME], f"unexpected outputs {outputs}"
    # Langflow checks the stored node before every tool call and refuses the call unless the node is in
    # tool mode ("Tool settings changed or are unavailable"; langflow AuthService.validate_tool_call).
    tpl["tool_mode"] = True
    return {
        "id": SEARCH_ID,
        "type": "genericNode",
        "position": {"x": 0, "y": 420},
        "data": {"id": SEARCH_ID, "type": "RuianSearch", "node": tpl, "showNode": True},
    }


def main() -> None:
    base = json.loads(BASE.read_text(encoding="utf-8"))
    nodes = {n["data"]["type"]: copy.deepcopy(n) for n in base["data"]["nodes"]}
    chat_in, agent, chat_out = nodes["ChatInput"], nodes["Agent"], nodes["ChatOutput"]
    agent["data"]["node"]["template"]["system_prompt"]["value"] = SYSTEM_PROMPT
    search = search_node()

    edges = [
        edge(
            chat_in["id"], {"dataType": "ChatInput", "id": chat_in["id"], "name": "message", "output_types": ["Message"]},
            agent["id"], {"fieldName": "input_value", "id": agent["id"], "inputTypes": ["Message"], "type": "str"},
        ),
        edge(
            SEARCH_ID, {"dataType": "RuianSearch", "id": SEARCH_ID, "name": TOOL_OUTPUT_NAME, "output_types": ["Tool"]},
            agent["id"], {"fieldName": "tools", "id": agent["id"], "inputTypes": ["Tool"], "type": "other"},
        ),
        edge(
            agent["id"], {"dataType": "Agent", "id": agent["id"], "name": "response", "output_types": ["Message"]},
            chat_out["id"],
            {"fieldName": "input_value", "id": chat_out["id"], "inputTypes": ["Data", "DataFrame", "Message"], "type": "str"},
        ),
    ]

    model = configure_agent_model(agent)

    flow = {
        "data": {"edges": edges, "nodes": [chat_in, agent, search, chat_out], "viewport": {"x": 100, "y": 50, "zoom": 0.8}},
        "description": (
            "Chat agent over the RUIAN address register. Tools come from the RUIAN Search component, "
            f"the model from the OpenAI Compatible provider ({model})."
        ),
        "endpoint_name": "ruian-agent",
        "icon": "map-pin",
        "icon_bg_color": None,
        "id": FLOW_ID,
        "is_component": False,
        "locked": False,
        "mcp_enabled": False,
        "name": "ruian-agent",
        "tags": [],
        "webhook": False,
    }
    # Sorted keys: the same bytes as `lfx pull`, so pulling the flow back from Langflow gives no diff.
    OUT.write_text(json.dumps(flow, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {OUT} (model {model})")


if __name__ == "__main__":
    main()
